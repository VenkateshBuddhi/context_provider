"""
Phase 3: Markdown Exporter for CONTEXT.md and HANDOFF.md.

Produces formatted documentation tailored for incoming AI coding agents:
- `CONTEXT.md`: High-level active state, current focus synthesized by llama3.1, and verified decisions.
- `HANDOFF.md`: Traps avoided synthesized by llama3.1 + LAYA, chronological history,
                and empirical failure evidence.
"""

from typing import List, Dict, Any, Optional
from context_provider.storage.models import ProjectRecord, SessionRecord, EpisodeRecord, EpisodeStatus, EventType


class MarkdownExporter:
    """Generates markdown context files from structured project records and local model syntheses."""

    @staticmethod
    def format_files_modified(files: List[str]) -> str:
        """
        Formats a list of modified files with truncation for Markdown rendering:
        - If empty: returns 'None'
        - If 5 or fewer files: returns comma-separated list
        - If more than 5 files: displays first 5 files followed by '...and X other files'
        """
        if not files:
            return "None"
        if len(files) <= 5:
            return ", ".join(files)
        first_five = ", ".join(files[:5])
        remaining = len(files) - 5
        return f"{first_five}, ...and {remaining} other files"

    _format_files_modified = format_files_modified

    def render_context_md(
        self,
        project: ProjectRecord,
        session: SessionRecord,
        episodes: List[EpisodeRecord],
        latest_git: Dict[str, Any],
        active_notes: List[str],
        synthesized_focus: Optional[str] = None,
    ) -> str:
        """Renders CONTEXT.md reflecting the current active developer state."""
        lines = [
            f"# Project Context: {project.name}",
            "",
            "> *Auto-generated by Local Context Provider. Powered by local LAYA + llama3.1.*",
            "",
            "## 1. Active Environment",
            f"- **Repository Path**: `{project.root_path}`",
            f"- **Active Session**: `{session.id}` (Started: {session.started_at[:19]} UTC)",
            f"- **Current Branch**: `{latest_git.get('branch', 'unknown')}`",
            f"- **HEAD Commit**: `{latest_git.get('head', 'unknown')[:8] if latest_git.get('head') else 'None'}`",
            "",
            "## 2. Current Focus & Objectives",
        ]

        if synthesized_focus:
            lines.append(synthesized_focus)
        elif active_notes:
            for note in active_notes[-5:]:
                lines.append(f"- {note}")
        else:
            lines.append("- *No active goals recorded.*")

        lines.extend([
            "",
            "## 3. Recent Episodes Summary",
            "| Episode Title | Status | Confidence | Touched Files |",
            "| :--- | :--- | :--- | :--- |",
        ])

        if episodes:
            for ep in episodes[-5:]:
                files_str = self.format_files_modified(ep.files_touched)
                lines.append(
                    f"| {ep.title} | `{ep.status.value}` | {ep.confidence_score:.2f} | {files_str} |"
                )
        else:
            lines.append("| No episodes completed yet | `pending` | - | - |")

        lines.extend([
            "",
            "---",
            "*For detailed failure logs and traps avoided, consult `HANDOFF.md`.*",
        ])

        return "\n".join(lines)

    def render_handoff_md(
        self,
        project: ProjectRecord,
        session: SessionRecord,
        episodes: List[EpisodeRecord],
        failed_attempts: List[Dict[str, Any]],
        traps_avoided: List[Dict[str, Any]],
        contradictions: List[Dict[str, Any]],
        synthesized_traps: Optional[str] = None,
    ) -> str:
        """Renders HANDOFF.md with evidence-backed logs of failures and abandoned approaches."""
        lines = [
            f"# Task Handoff Dossier: {project.name}",
            "",
            "> *CRITICAL FOR INCOMING AI AGENTS: Read this document before attempting fixes.*",
            "> *It records verified attempts, failures, and traps already encountered.*",
            "",
            "## 1. Actionable Traps to Avoid (DO NOT REPEAT)",
        ]

        if synthesized_traps:
            lines.extend([
                synthesized_traps,
                "",
                "### Supporting Empirical Findings:",
            ])

        has_findings = bool(traps_avoided or failed_attempts or contradictions)

        if has_findings:
            for c in contradictions:
                lines.extend([
                    f"### LAYA Conflict Detection: {c.get('type')}",
                    f"- **Premise**: \"{c.get('premise_note')}\"",
                    f"- **Invalidating Evidence**: {c.get('invalidating_evidence')}",
                    f"- **Model Confidence**: {c.get('confidence'):.2f} (via {c.get('evaluator')})",
                    "",
                ])
            for trap in traps_avoided:
                lines.extend([
                    f"### Pattern: {trap.get('pattern', 'ANOMALY')}",
                    f"- **Severity**: {trap.get('severity', 'MEDIUM')}",
                    f"- **Finding**: {trap.get('description', '')}",
                    f"- **Timestamp**: {trap.get('timestamp', '')}",
                    "",
                ])
            for fa in failed_attempts:
                lines.extend([
                    f"### Abandoned Attempt: {fa.get('title', 'Failed Task')}",
                    f"- **Outcome**: `{fa.get('status', 'abandoned')}`",
                    f"- **Files**: {self.format_files_modified(fa.get('files', []))}",
                    f"- **Failure Evidence**: {fa.get('evidence', 'Changes reverted or abandoned.')}",
                    "",
                ])
        elif not synthesized_traps:
            lines.append("- *No known failure loops or discarded branches detected.*")
            lines.append("")

        lines.extend([
            "## 2. Chronological Episode Record",
        ])

        if not episodes:
            lines.append("- *No high-signal episodes recorded.*")
            lines.append("")
        else:
            for ep in episodes:
                status_str = ep.status.value.upper() if hasattr(ep.status, "value") else str(ep.status).upper()
                lines.extend([
                    f"### {ep.title} (`{status_str}`)",
                    f"- **Timeframe**: {ep.started_at[:19]} to {ep.ended_at[:19] if ep.ended_at else 'ongoing'}",
                    f"- **Confidence Score**: {ep.confidence_score:.2f}",
                    f"- **Files Modified**: {self.format_files_modified(ep.files_touched)}",
                ])
                if ep.summary:
                    lines.append(f"- **Summary**:\n{ep.summary}")
                lines.append("")

        return "\n".join(lines)
